export function parseMagicTypeLineSelection(value: string): string[] {
  const words = value.trim().split(/\s+/).filter(Boolean);
  const selected: string[] = [];
  let index = 0;
  while (index < words.length) {
    let matched: string | undefined;
    let take = 1;
    const room = Math.min(6, words.length - index);
    for (let size = room; size >= 1; size -= 1) {
      const phrase = words.slice(index, index + size).join(" ").toLowerCase();
      const canonical = MAGIC_TYPE_LINE_BY_LOWER.get(phrase);
      if (canonical) {
        matched = canonical;
        take = size;
        break;
      }
    }
    selected.push(matched ?? words[index]!);
    index += take;
  }
  return selected;
}

export function toggleMagicTypeLineSelection(value: string, option: string): string {
  const canonical = MAGIC_TYPE_LINE_BY_LOWER.get(option.toLowerCase()) ?? option;
  const current = parseMagicTypeLineSelection(value);
  const has = current.some((item) => item.toLowerCase() === canonical.toLowerCase());
  const next = has
    ? current.filter((item) => item.toLowerCase() !== canonical.toLowerCase())
    : [...current, canonical];
  return next.join(" ");
}
